export function visualText(locale: PreviewLocale, key: VisualKey, values: Record<string, string | number> = {}): string {
  return visualMessages[locale][key].replace(/\{(\w+)\}/gu, (token, name: string) => Object.hasOwn(values, name) ? String(values[name]) : token);
}
// Only the gallery's exact variant label can be translated by this registry.
export function galleryName(id: string, original: string, locale: PreviewLocale): string {
  const row = Object.hasOwn(galleryNames, id) ? galleryNames[id] : undefined;
  return row?.[0] === original ? row[localeOrder.indexOf(locale)] ?? original : original;
}
